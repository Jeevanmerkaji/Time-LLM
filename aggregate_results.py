"""
Aggregate results_full_rigor.jsonl into mean +/- std per (profile_id, method)
across seeds, for the arXiv writeup's full-rigor results table.

Only status=="ok" rows count. Safe to run against a partial matrix -- each
row reports how many of the 3 seeds are actually in (e.g. "2/3") so it's
obvious which cells are still incomplete.

Usage:
    python aggregate_results.py
    python aggregate_results.py --out results_full_rigor_summary.md
"""

import argparse
import json
import statistics
from collections import defaultdict
from pathlib import Path

SESSIONS = [70, 62, 44]
METHODS = ["dlinear", "lstm", "time_llm"]
METHOD_LABEL = {"dlinear": "DLinear", "lstm": "LSTM", "time_llm": "Time-LLM (frozen GPT-2)"}
EXPECTED_SEEDS = 3


def load(path):
    rows = defaultdict(list)
    for line in Path(path).read_text().splitlines():
        if not line.strip():
            continue
        rec = json.loads(line)
        if rec.get("status") != "ok":
            continue
        key = (rec["profile_id"], rec["method"])
        rows[key].append(rec)
    return rows


def fmt(mean, std, n):
    if n == 1:
        return f"{mean:.4f} (n=1)"
    return f"{mean:.4f} ± {std:.4f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--jsonl", default="results_full_rigor.jsonl")
    ap.add_argument("--out", default="results_full_rigor_summary.md")
    args = ap.parse_args()

    rows = load(args.jsonl)

    lines = []
    lines.append("# Full-rigor results summary\n")
    lines.append(
        "Mean ± std across seeds, per (Kaggle `profile_id`, method). "
        "Auto-generated by `aggregate_results.py` -- re-run after every "
        "completed run to refresh.\n"
    )

    total_done = sum(len(v) for v in rows.values())
    total_expected = len(SESSIONS) * len(METHODS) * EXPECTED_SEEDS
    lines.append(f"**Progress: {total_done}/{total_expected} runs complete.**\n")

    for profile_id in SESSIONS:
        lines.append(f"\n## profile_id={profile_id}\n")
        lines.append("| Method | Test MSE | Test MAE | Train time (mean) | Seeds |")
        lines.append("|---|---|---|---|---|")
        for method in METHODS:
            recs = rows.get((profile_id, method), [])
            n = len(recs)
            if n == 0:
                lines.append(f"| {METHOD_LABEL[method]} | -- | -- | -- | 0/{EXPECTED_SEEDS} |")
                continue
            mses = [r["test_mse"] for r in recs]
            maes = [r["test_mae"] for r in recs]
            times = [r["elapsed_s"] for r in recs]
            mse_mean, mse_std = statistics.mean(mses), (statistics.stdev(mses) if n > 1 else 0.0)
            mae_mean, mae_std = statistics.mean(maes), (statistics.stdev(maes) if n > 1 else 0.0)
            t_mean = statistics.mean(times)
            seeds_present = sorted(r["seed"] for r in recs)
            lines.append(
                f"| {METHOD_LABEL[method]} | {fmt(mse_mean, mse_std, n)} | "
                f"{fmt(mae_mean, mae_std, n)} | {t_mean/3600:.2f}h | "
                f"{n}/{EXPECTED_SEEDS} (seeds {seeds_present}) |"
            )

    # Cross-session summary: mean of per-session means, per method (only for
    # methods complete on all 3 sessions).
    lines.append("\n## Cross-session summary (mean of per-session means)\n")
    lines.append("| Method | Mean Test MSE | Mean Test MAE | Sessions complete |")
    lines.append("|---|---|---|---|")
    for method in METHODS:
        session_means_mse = []
        session_means_mae = []
        complete_sessions = 0
        for profile_id in SESSIONS:
            recs = rows.get((profile_id, method), [])
            if len(recs) == EXPECTED_SEEDS:
                complete_sessions += 1
                session_means_mse.append(statistics.mean(r["test_mse"] for r in recs))
                session_means_mae.append(statistics.mean(r["test_mae"] for r in recs))
        if complete_sessions == 0:
            lines.append(f"| {METHOD_LABEL[method]} | -- | -- | 0/{len(SESSIONS)} |")
        else:
            lines.append(
                f"| {METHOD_LABEL[method]} | {statistics.mean(session_means_mse):.4f} | "
                f"{statistics.mean(session_means_mae):.4f} | {complete_sessions}/{len(SESSIONS)} |"
            )

    out_text = "\n".join(lines) + "\n"
    Path(args.out).write_text(out_text)
    print(out_text)
    print(f"Written to {args.out}")


if __name__ == "__main__":
    main()
